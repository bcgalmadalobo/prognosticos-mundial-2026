/**
 * Returns the third-place slot assignment for the given combination of 8 qualified groups.
 * @param qualifiedGroups Array of exactly 8 group letters (e.g. ["A","B","C","D","E","F","G","H"])
 * @throws Error if the combination is not found in the allocation table
 */
export function getThirdPlaceAssignment(qualifiedGroups: string[]): ThirdPlaceAssignment {
  if (qualifiedGroups.length !== 8) {
    throw new Error(`getThirdPlaceAssignment: esperados 8 grupos, recebidos ${qualifiedGroups.length}`);
  }
  const key = [...qualifiedGroups].sort().join('');
  const assignment = THIRD_PLACE_ALLOCATION[key];
  if (!assignment) {
    throw new Error(`Combinação de terceiros não encontrada na tabela: ${key}`);
  }
  return assignment;
}
